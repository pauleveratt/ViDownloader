# ViDownloader installer
# - downloads yt-dlp.exe into .\bin (or updates it)
# - checks for Node.js and ffmpeg (installs ffmpeg via winget if missing)
# - writes helper\config.json with a random access token
# - creates a hidden launcher + Startup shortcut so the helper runs at login
# - (re)starts the helper and copies the token to the clipboard
param(
    [switch]$NoStartup  # don't add the Windows Startup shortcut
)
$ErrorActionPreference = 'Stop'
$root   = $PSScriptRoot
$bin    = Join-Path $root 'bin'
$helper = Join-Path $root 'helper'
$utf8   = New-Object System.Text.UTF8Encoding $false
New-Item -ItemType Directory -Force $bin | Out-Null

Write-Host "`n== ViDownloader setup ==" -ForegroundColor Cyan

# --- Node.js -----------------------------------------------------------------
$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { throw 'Node.js was not found. Install the LTS version from https://nodejs.org and run this again.' }
Write-Host "Node.js : $node ($(& $node --version))"

# --- ffmpeg ------------------------------------------------------------------
function Find-Ffmpeg {
    $cmd = Get-Command ffmpeg -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    $wingetDir = Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Packages'
    if (Test-Path $wingetDir) {
        $hit = Get-ChildItem $wingetDir -Recurse -Filter ffmpeg.exe -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($hit) { return $hit.FullName }
    }
    return $null
}
$ffmpeg = Find-Ffmpeg
if (-not $ffmpeg) {
    Write-Host 'ffmpeg not found - installing with winget...' -ForegroundColor Yellow
    winget install --id Gyan.FFmpeg -e --accept-source-agreements --accept-package-agreements
    $ffmpeg = Find-Ffmpeg
    if (-not $ffmpeg) { throw 'ffmpeg install failed. Install it manually (winget install Gyan.FFmpeg) and run this again.' }
}
Write-Host "ffmpeg  : $ffmpeg"

# --- yt-dlp ------------------------------------------------------------------
$ytdlp = Join-Path $bin 'yt-dlp.exe'
if (Test-Path $ytdlp) {
    Write-Host 'yt-dlp  : updating...'
    & $ytdlp -U | Out-Host
} else {
    Write-Host 'yt-dlp  : downloading latest release from GitHub...'
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    Invoke-WebRequest 'https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp.exe' -OutFile $ytdlp -UseBasicParsing
}
Write-Host "yt-dlp  : $(& $ytdlp --version)"

# --- config ------------------------------------------------------------------
$configPath = Join-Path $helper 'config.json'
$config = [ordered]@{}
if (Test-Path $configPath) {
    (Get-Content $configPath -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object { $config[$_.Name] = $_.Value }
}
if (-not $config.token) {
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $config.token = -join ($bytes | ForEach-Object { $_.ToString('x2') })
}
if (-not $config.port)      { $config.port = 47321 }
if (-not $config.outputDir) { $config.outputDir = Join-Path ([Environment]::GetFolderPath('MyVideos')) 'ViDownloader' }
$config.ffmpegPath = $ffmpeg
$config.ytdlpPath  = $ytdlp
$config.nodePath   = $node
[IO.File]::WriteAllText($configPath, ($config | ConvertTo-Json), $utf8)
New-Item -ItemType Directory -Force $config.outputDir | Out-Null
Write-Host "Output  : $($config.outputDir)"

# --- hidden launcher + Startup shortcut --------------------------------------
$vbs = Join-Path $root 'start-helper.vbs'
$server = Join-Path $helper 'server.js'
$vbsText = @"
' Starts the ViDownloader helper with no console window (generated by install.ps1)
Set sh = CreateObject("WScript.Shell")
sh.CurrentDirectory = "$helper"
sh.Run """$node"" ""$server""", 0, False
"@
[IO.File]::WriteAllText($vbs, $vbsText, [Text.Encoding]::ASCII)

$lnkPath = Join-Path ([Environment]::GetFolderPath('Startup')) 'ViDownloader Helper.lnk'
if ($NoStartup) {
    if (Test-Path $lnkPath) { Remove-Item $lnkPath }
} else {
    $sh = New-Object -ComObject WScript.Shell
    $lnk = $sh.CreateShortcut($lnkPath)
    $lnk.TargetPath = "$env:WINDIR\System32\wscript.exe"
    $lnk.Arguments = "`"$vbs`""
    $lnk.WorkingDirectory = $helper
    $lnk.Description = 'ViDownloader local helper'
    $lnk.Save()
    Write-Host "Startup : helper will start automatically at login"
}

# --- (re)start helper --------------------------------------------------------
Get-CimInstance Win32_Process -Filter "Name='node.exe'" |
    Where-Object { $_.CommandLine -like "*$server*" } |
    ForEach-Object { Stop-Process -Id $_.ProcessId -Force }
Start-Process "$env:WINDIR\System32\wscript.exe" -ArgumentList "`"$vbs`""
Start-Sleep -Seconds 2
try {
    $ping = Invoke-RestMethod "http://127.0.0.1:$($config.port)/ping" -Headers @{ 'X-ViD-Token' = $config.token } -TimeoutSec 5
    Write-Host "Helper  : running (v$($ping.version))" -ForegroundColor Green
} catch {
    Write-Host "Helper  : did not respond yet - check helper\logs\helper.log" -ForegroundColor Yellow
}

Set-Clipboard -Value $config.token
Write-Host "`nAccess token (copied to clipboard):" -ForegroundColor Cyan
Write-Host "  $($config.token)"
Write-Host @"

Next steps:
  1. Open chrome://extensions and turn on Developer mode (top right)
  2. Click 'Load unpacked' and pick: $(Join-Path $root 'extension')
  3. The extension's settings page opens - paste the token there.
"@
